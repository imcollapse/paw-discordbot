// paw — generate discord <thing>. Fake Discord screenshots, drawn locally (no AI).
// Slash:  /generate discord message text:hi badges:nitro,staff tag:PAW
// Prefix: ,generate discord message hi there --badges nitro,staff --tag PAW
// Output is just the image with a tiny "-#" line above it. No container.

const { SlashCommandBuilder, AttachmentBuilder } = require('discord.js');
const ui = require('../../../services/ui');
const gen = require('../../../services/generate/discord');

const NO_MENTIONS = { parse: [] };
const LINE = '-# fake image generated by paw';
const STATUSES = ['online', 'idle', 'dnd', 'offline'];

// slash definition

// who the message is "from" — every option is optional
const person = (s) => s
  .addUserOption(o => o.setName('user').setDescription('Take name and avatar from this person (default: you)'))
  .addStringOption(o => o.setName('name').setDescription('Display name shown instead'))
  .addAttachmentOption(o => o.setName('avatar').setDescription('Avatar image to use instead'))
  .addStringOption(o => o.setName('color').setDescription('Name colour as hex, like #ff66aa'))
  .addStringOption(o => o.setName('badges').setDescription('Badge keys, comma separated. See /generate discord badges'))
  .addStringOption(o => o.setName('tag').setDescription('Server tag text, 2 to 4 letters, like PAW'))
  .addAttachmentOption(o => o.setName('tag_icon').setDescription('Small icon shown inside the server tag'))
  .addBooleanOption(o => o.setName('bot').setDescription('Show the APP label'))
  .addStringOption(o => o.setName('time').setDescription('Time text, like "Today at 4:20 PM"'));

const str = (s, name, desc, req = false) => s.addStringOption(o => o.setName(name).setDescription(desc).setRequired(req));
const att = (s, name, desc) => s.addAttachmentOption(o => o.setName(name).setDescription(desc));

const sub = (n, d, fn) => (g) => g.addSubcommand(s => fn(s.setName(n).setDescription(d)));

const data = new SlashCommandBuilder().setName('generate').setDescription('Make fake Discord screenshots')
  .addSubcommandGroup(g => {
    g.setName('discord').setDescription('Fake Discord screenshots');
    sub('message', 'A single fake message', s => { str(s, 'text', 'What the message says', true); att(s, 'image', 'Picture to attach'); s.addBooleanOption(o => o.setName('edited').setDescription('Show (edited)')); return person(s); })(g);
    sub('reply', 'A fake message replying to another', s => { str(s, 'text', 'What the message says', true); str(s, 'reply_text', 'The message being replied to', true); s.addUserOption(o => o.setName('reply_user').setDescription('Who wrote the original')); str(s, 'reply_name', 'Name of the original author'); return person(s); })(g);
    sub('convo', 'A fake conversation', s => { str(s, 'messages', 'Name: text | Name: text | ...', true); return s; })(g);
    sub('quote', 'A quote card', s => { str(s, 'text', 'The quote', true); return person(s); })(g);
    sub('profile', 'A fake profile popout', s => { person(s); str(s, 'username', 'Username under the name'); att(s, 'banner', 'Banner image'); str(s, 'banner_color', 'Banner colour as hex'); str(s, 'status', 'online, idle, dnd or offline'); str(s, 'custom_status', 'Custom status text'); str(s, 'pronouns', 'Pronouns'); str(s, 'bio', 'About me'); str(s, 'since', 'Member since, like "Jan 3, 2020"'); str(s, 'roles', 'Role:#colour, Role:#colour'); return s; })(g);
    sub('minimized-profile', 'A small fake profile popout', s => { person(s); str(s, 'username', 'Username under the name'); att(s, 'banner', 'Banner image'); str(s, 'banner_color', 'Banner colour as hex'); str(s, 'status', 'online, idle, dnd or offline'); str(s, 'custom_status', 'Custom status text'); return s; })(g);
    sub('apply', 'A fake "apply to join" form', s => { str(s, 'server', 'Server name', true); str(s, 'questions', 'Questions separated by |', true); str(s, 'answers', 'Answers separated by | (same order)'); att(s, 'icon', 'Server icon'); str(s, 'description', 'Short description'); str(s, 'members', 'Member count text, like 5,730'); str(s, 'online', 'Online count text, like 1,204'); return s; })(g);
    sub('user-switcher', 'A fake account switcher', s => { str(s, 'accounts', 'Name:status | Name:status (first one is active)'); return s; })(g);
    sub('badges', 'List every badge key you can use', s => s)(g);
    return g;
  });

// reading input from either side

const FLAG = /(?:^|\s)--([a-z][a-z_-]*)(?=\s|$)/gi;

/** "hello world --badges nitro --tag PAW" → { rest: 'hello world', flags: { badges: 'nitro', tag: 'PAW' } } */
function splitFlags(raw) {
  const flags = {}; const marks = []; let m;
  while ((m = FLAG.exec(raw))) marks.push({ key: m[1].toLowerCase().replace(/-/g, '_'), start: m.index, end: m.index + m[0].length });
  const rest = (marks.length ? raw.slice(0, marks[0].start) : raw).trim();
  marks.forEach((k, i) => { const v = raw.slice(k.end, marks[i + 1]?.start ?? raw.length).trim(); flags[k.key] = v === '' ? true : v; });
  return { rest, flags };
}

const truthy = (v) => v === true || /^(1|true|yes|on|y)$/i.test(String(v || ''));

async function read(ctx, args, isSlash) {
  if (isSlash) {
    const o = ctx.options;
    const g = (n) => o.getString(n) ?? undefined;
    return {
      sub: o.getSubcommand(),
      user: o.getUser('user') || null, replyUser: o.getUser('reply_user') || null,
      text: g('text') ?? g('messages') ?? '',
      v: Object.fromEntries(['name', 'color', 'badges', 'tag', 'time', 'reply_text', 'reply_name', 'username', 'banner_color', 'status', 'custom_status', 'pronouns', 'bio', 'since', 'roles', 'server', 'questions', 'answers', 'description', 'members', 'online', 'accounts'].map(k => [k, g(k)])),
      bot: o.getBoolean('bot') ?? false, edited: o.getBoolean('edited') ?? false,
      avatar: o.getAttachment('avatar')?.url, image: o.getAttachment('image')?.url, tagIcon: o.getAttachment('tag_icon')?.url,
      banner: o.getAttachment('banner')?.url, icon: o.getAttachment('icon')?.url,
    };
  }
  const list = [...args];
  if (list[0]?.toLowerCase() === 'discord') list.shift();
  const subName = (list.shift() || '').toLowerCase();
  const { rest, flags } = splitFlags(list.join(' '));
  // a leading mention or id picks the person
  let text = rest; let user = null;
  const first = text.split(/\s+/)[0] || '';
  const id = first.match(/^<@!?(\d{17,20})>$/)?.[1] || (/^\d{17,20}$/.test(first) ? first : null);
  if (id) { user = ctx.mentions.users.get(id) || await ctx.client.users.fetch(id).catch(() => null); if (user) text = text.slice(first.length).trim(); }
  // <@id> inside the text reads as @name
  text = text.replace(/<@!?(\d{17,20})>/g, (_, i) => `@${ctx.mentions.users.get(i)?.username || 'user'}`);
  const files = [...ctx.attachments.values()].map(a => a.url);
  const replyUser = flags.reply_user ? (ctx.mentions.users.find(u => flags.reply_user.includes(u.id)) || null) : null;
  const clean = (x) => (x === true ? undefined : x);
  const v = {}; for (const [k, val] of Object.entries(flags)) v[k] = clean(val);
  if (flags.reply && !v.reply_text) v.reply_text = clean(flags.reply);
  if (v.tagicon) v.tag = v.tag;
  return {
    sub: subName, user, replyUser, text, v, bot: truthy(flags.bot), edited: truthy(flags.edited),
    avatar: /^https?:\/\//.test(flags.avatar || '') ? flags.avatar : undefined,
    image: files[0] || (/^https?:\/\//.test(flags.image || '') ? flags.image : undefined),
    tagIcon: /^https?:\/\//.test(flags.tag_icon || '') ? flags.tag_icon : undefined,
    banner: files[0] && subName.includes('profile') ? files[0] : (/^https?:\/\//.test(flags.banner || '') ? flags.banner : undefined),
    icon: files[0] && subName === 'apply' ? files[0] : (/^https?:\/\//.test(flags.icon || '') ? flags.icon : undefined),
  };
}

// turning input into render data

const avatarOf = (u) => u?.displayAvatarURL?.({ extension: 'png', size: 256, forceStatic: true });
const nowText = () => { const d = new Date(); let h = d.getHours(); const ap = h >= 12 ? 'PM' : 'AM'; h = h % 12 || 12; return `Today at ${h}:${String(d.getMinutes()).padStart(2, '0')} ${ap}`; };

function memberColor(member) {
  const c = member?.displayHexColor;
  return c && c !== '#000000' ? c : undefined;
}

/** The person in the picture: explicit options win, then the chosen user, then whoever ran it. */
function who(guild, author, d) {
  const u = d.user || author;
  const member = guild.members.cache.get(u.id);
  const { keys, unknown } = gen.parseBadges(d.v.badges);
  return {
    unknown,
    p: {
      name: d.v.name || member?.displayName || u.displayName || u.username,
      username: u.username,
      color: gen.hexOk(d.v.color) ? d.v.color : memberColor(member),
      avatar: d.avatar || avatarOf(member || u),
      badges: keys, tag: d.v.tag ? String(d.v.tag).slice(0, 4) : undefined, tagIcon: d.tagIcon,
      bot: d.bot || (!d.user && false), time: d.v.time || nowText(),
    },
  };
}

function lookup(guild, name, author) {
  const n = name.toLowerCase();
  const m = guild.members.cache.find(x => x.displayName.toLowerCase() === n || x.user.username.toLowerCase() === n) || (author.username.toLowerCase() === n ? guild.members.cache.get(author.id) : null);
  return m ? { avatar: avatarOf(m), color: memberColor(m) } : {};
}

const split = (s) => String(s || '').split('|').map(x => x.trim()).filter(Boolean);

// reply helpers

async function fail(ctx, isSlash, msg) {
  if (isSlash) return ctx.deferred || ctx.replied ? ctx.editReply({ content: msg }) : ctx.reply({ content: msg, flags: 64 });
  return ui.say.error(ctx, msg);
}

function badgeList() {
  const lines = Object.entries(gen.BADGES).map(([k, [, label]]) => `\`${k}\` ${label}`);
  return [
    '**Badge keys** — use them in `badges`, separated by commas',
    ...lines,
    '',
    'Example: `badges:nitro,bravery,staff`',
    '-# also: tag:PAW adds a server tag · bot:true adds the APP label',
  ].join('\n');
}

function usage() {
  return [
    '**generate discord** — fake screenshots, made by paw',
    '`message` `reply` `convo` `quote` `profile` `minimized-profile` `apply` `user-switcher` `badges`',
    '',
    'Prefix: `,generate discord message hello --badges nitro --tag PAW`',
    'Slash: `/generate discord message text:hello badges:nitro tag:PAW`',
    'Everything after `--` is optional: name, color, avatar, badges, tag, tag_icon, bot, time',
    'Run `generate discord badges` to see every badge key.',
  ].join('\n');
}

// command

module.exports = {
  data,
  name: 'generate',
  description: 'Make fake Discord screenshots (message, reply, convo, quote, profile, apply, user-switcher)',
  aliases: ['gen', 'fake'],
  category: 'fun',
  usage: 'generate discord <message|reply|convo|quote|profile|minimized-profile|apply|user-switcher|badges> <text> [--badges nitro] [--tag PAW]',

  async execute(ctx, args = []) {
    const isSlash = ctx.isChatInputCommand?.();
    const guild = ctx.guild;
    const author = isSlash ? ctx.user : ctx.author;
    if (!guild) return fail(ctx, isSlash, 'Use this in a server');

    const d = await read(ctx, args, isSlash);
    if (!d.sub) return isSlash ? fail(ctx, isSlash, usage()) : ctx.reply({ content: usage(), allowedMentions: NO_MENTIONS });
    if (d.sub === 'badges') return isSlash ? ctx.reply({ content: badgeList(), flags: 64 }) : ctx.reply({ content: badgeList(), allowedMentions: NO_MENTIONS });

    const needs = { message: 'text', reply: 'text', quote: 'text', convo: 'messages', apply: 'server' };
    if (isSlash) await ctx.deferReply();
    if (needs[d.sub] && !d.text && d.sub !== 'apply') return fail(ctx, isSlash, `Add the ${needs[d.sub]}. Try: \`generate discord ${d.sub} hello there\``);

    try {
      let buffer;
      const { p, unknown } = who(guild, author, d);
      if (unknown.length) return fail(ctx, isSlash, `Unknown badge${unknown.length > 1 ? 's' : ''}: ${unknown.map(x => `\`${x}\``).join(', ')}. Run \`generate discord badges\` for the list`);

      if (d.sub === 'message') {
        buffer = await gen.renderMessages([{ ...p, text: d.text, image: d.image, edited: d.edited }]);
      } else if (d.sub === 'reply') {
        if (!d.v.reply_text) return fail(ctx, isSlash, 'Add the message being replied to. Prefix: `--reply some text`');
        const ru = d.replyUser; const rm = ru && guild.members.cache.get(ru.id);
        const rname = d.v.reply_name || rm?.displayName || ru?.username || 'someone';
        buffer = await gen.renderMessages([{ ...p, text: d.text, reply: { name: rname, color: memberColor(rm), avatar: ru ? avatarOf(rm || ru) : undefined, text: d.v.reply_text } }]);
      } else if (d.sub === 'convo') {
        const msgs = split(d.text).map(line => { const i = line.indexOf(':'); return i > 0 ? { name: line.slice(0, i).trim(), text: line.slice(i + 1).trim() } : null; }).filter(m => m?.text).slice(0, 12);
        if (msgs.length < 1) return fail(ctx, isSlash, 'Write it like `Name: text | Name: text`');
        let prev = null; const t0 = new Date(); let minutes = t0.getMinutes() - msgs.length;
        const list = msgs.map((m, i) => {
          const same = prev === m.name.toLowerCase(); prev = m.name.toLowerCase();
          const when = new Date(t0); when.setMinutes(minutes + i);
          let h = when.getHours(); const ap = h >= 12 ? 'PM' : 'AM'; h = h % 12 || 12;
          return { name: m.name, text: m.text, grouped: same, time: `Today at ${h}:${String(when.getMinutes()).padStart(2, '0')} ${ap}`, ...lookup(guild, m.name, author) };
        });
        buffer = await gen.renderMessages(list);
      } else if (d.sub === 'quote') {
        buffer = await gen.renderQuote({ name: p.name, color: p.color, avatar: p.avatar, tag: p.tag, tagIcon: p.tagIcon, text: d.text });
      } else if (d.sub === 'profile' || d.sub === 'minimized-profile') {
        const status = STATUSES.includes(String(d.v.status).toLowerCase()) ? String(d.v.status).toLowerCase() : 'online';
        const roles = split(d.v.roles?.replace(/,/g, '|')).slice(0, 8).map(r => { const [n, c] = r.split(':'); return { name: n.trim(), color: c?.trim() }; });
        buffer = await gen.renderProfile({
          name: p.name, username: d.v.username || p.username, avatar: p.avatar, banner: d.banner, bannerColor: d.v.banner_color || p.color,
          badges: p.badges, tag: p.tag, tagIcon: p.tagIcon, status, customStatus: d.v.custom_status, pronouns: d.v.pronouns,
          bio: d.v.bio, since: d.v.since, roles,
        }, { compact: d.sub === 'minimized-profile' });
      } else if (d.sub === 'apply') {
        const server = d.v.server || d.text;
        const questions = split(d.v.questions);
        if (!server || !questions.length) return fail(ctx, isSlash, 'Add a server name and questions: `--server My Server --questions Why join? | How old are you?`');
        buffer = await gen.renderApply({ server, questions, answers: split(d.v.answers), icon: d.icon, description: d.v.description, members: d.v.members, online: d.v.online });
      } else if (d.sub === 'user-switcher') {
        const me = guild.members.cache.get(author.id);
        const parsed = split(d.v.accounts || d.text).map(s => { const [n, st] = s.split(':'); const l = lookup(guild, n.trim(), author); return { name: n.trim(), status: STATUSES.includes((st || '').trim().toLowerCase()) ? st.trim().toLowerCase() : 'online', avatar: l.avatar }; });
        const accounts = parsed.length ? parsed : [{ name: me?.displayName || author.username, username: author.username, avatar: avatarOf(me || author), status: 'online' }, { name: 'Alt Account', status: 'idle' }];
        buffer = await gen.renderSwitcher(accounts);
      } else {
        return fail(ctx, isSlash, usage());
      }

      const payload = { content: LINE, files: [new AttachmentBuilder(buffer, { name: `paw-${d.sub}.png` })], allowedMentions: NO_MENTIONS };
      return isSlash ? ctx.editReply(payload) : ctx.reply(payload);
    } catch (e) {
      console.error('[generate]', e);
      return fail(ctx, isSlash, 'Could not draw that one. Check your options and try again');
    }
  },
};
