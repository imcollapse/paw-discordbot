const TAG = /^<a?:\w+:\d+>$/;
const isCustom = (v) => typeof v === 'string' && TAG.test(v);

/** Custom emoji tag for a key, or undefined when none is configured. */
const customOf = (key) => (isCustom(custom[key]) ? custom[key] : undefined);

/** key -> custom emoji if set, otherwise its text fallback. */
const emojis = {};
function rebuild() {
  for (const key of new Set([...Object.keys(FALLBACK), ...Object.keys(custom)])) {
    emojis[key] = customOf(key) ?? FALLBACK[key] ?? '';
  }
}
rebuild();

/** Re-read emojis.json contents (used by the reload command). */
function reload(fresh) {
  for (const k of Object.keys(custom)) delete custom[k];
  Object.assign(custom, fresh);
  rebuild();
}

module.exports = emojis;
Object.defineProperties(module.exports, {
  FALLBACK: { value: FALLBACK }, isCustom: { value: isCustom }, customOf: { value: customOf }, reload: { value: reload },
});
